"""Ties the detected hardware to the models Ollama actually has installed.

Everything here describes the machine running this backend (see core/hardware.py).
It never changes routing by itself, with one exception that is deliberate and
loud: `ensure_runnable` refuses a model that clearly cannot fit, with a message
that names alternatives. It never switches to a cloud model.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional

from config import settings
from core import hardware, model_catalog as catalog
from providers.base import ModelInfo, ModelUnavailable
from providers.registry import providers


def _ollama():
    return providers().get("ollama")


def _params_b(parameter_size: Optional[str]) -> Optional[float]:
    """"7.6B" -> 7.6, "135M" -> 0.135."""
    if not parameter_size:
        return None
    match = re.match(r"\s*([\d.]+)\s*([bm])", parameter_size, re.I)
    if not match:
        return None
    value = float(match.group(1))
    return value if match.group(2).lower() == "b" else value / 1000


def _installed() -> List[ModelInfo]:
    provider = _ollama()
    if provider is None:
        return []
    try:
        return list(provider.health().models)
    except Exception:  # noqa: BLE001
        return []


def _facts(model: ModelInfo) -> Dict[str, Any]:
    """Size, architecture and licence for one installed model."""
    provider = _ollama()
    shown: Dict[str, Any] = {}
    show = getattr(provider, "show", None)
    if show:
        try:
            shown = show(model.id) or {}
        except Exception:  # noqa: BLE001
            shown = {}
    entry = catalog.catalog_entry(model.id)
    # Decimal GB, like Ollama's own listings and the catalogue's download sizes.
    weights_gb = (model.size_bytes / 1e9) if model.size_bytes else (entry.download_gb if entry else None)
    kv = catalog.kv_bytes_per_token(shown.get("model_info"), entry.kv_bytes_per_token if entry else None)
    return {
        "weights_gb": weights_gb,
        "params_b": _params_b(model.parameter_size) or (entry.params_b if entry else None),
        "kv": kv,
        "license": catalog.classify_license(shown.get("license")) if shown else None,
        "catalog": entry,
    }


def _find(model_id: str) -> Optional[ModelInfo]:
    for m in _installed():
        if m.id == model_id or m.id == f"{model_id}:latest":
            return m
    return None


def effective_context(model_id: str) -> int:
    """Context window to request: the configured value, lowered if this machine
    can't hold that much for this model without running worse."""
    cap = settings.local_num_ctx
    info = _find(model_id)
    if not info:
        return cap
    facts = _facts(info)
    if facts["weights_gb"] is None:
        return cap
    try:
        hw = hardware.detect()
        return min(cap, catalog.best_context(hw, facts["weights_gb"], facts["params_b"], facts["kv"], cap))
    except Exception:  # noqa: BLE001
        return cap


def assess_model(model_id: str) -> Optional[Dict[str, Any]]:
    """Fit of one installed model on this machine, or None if it can't be judged."""
    info = _find(model_id)
    if not info:
        return None
    facts = _facts(info)
    if facts["weights_gb"] is None:
        return None
    hw = hardware.detect()
    ctx = min(settings.local_num_ctx, catalog.best_context(hw, facts["weights_gb"], facts["params_b"], facts["kv"], settings.local_num_ctx))
    return catalog.assess(hw, facts["weights_gb"], facts["params_b"], facts["kv"], ctx)


def suggest_alternatives(exclude: str = "") -> List[Dict[str, str]]:
    """Explicit things the user can do, in order. Each is something THEY choose."""
    hw = hardware.detect()
    installed_ids = [m.id for m in _installed()]
    rec = catalog.recommend(hw, installed_ids, settings.commercial_use, settings.local_num_ctx)
    out: List[Dict[str, str]] = []
    pick = rec["recommended"]
    if pick and pick["model"] != exclude:
        if pick["installed"]:
            out.append({"action": "use_model", "model": pick["model"], "text": f"Use {pick['label']}, which is already installed and suits this machine."})
        else:
            out.append({"action": "install_model", "model": pick["model"], "text": f"Install {pick['label']}: ollama pull {pick['model']}"})
    out.append({"action": "switch_mode", "mode": "cloud", "text": "Switch to Cloud mode in Settings (replies are then generated by the cloud provider)."})
    return out


def ensure_runnable(model_id: str) -> None:
    """Raise ModelUnavailable, with alternatives, if the model clearly can't run
    here. Does nothing when it can't be judged (unknown size, Ollama down,
    RINTI_HARDWARE_CHECK=false)."""
    if not settings.hardware_check:
        return
    try:
        result = assess_model(model_id)
    except Exception:  # noqa: BLE001 - never block chat because detection failed
        return
    if result is None or result["fits"]:
        return
    options = " ".join(a["text"] for a in suggest_alternatives(exclude=model_id)[:2])
    raise ModelUnavailable(
        f"{model_id} is too large to run well on this computer. {' '.join(result['reasons'])} "
        f"Nothing was sent to the cloud. {options}"
    )


def overview() -> Dict[str, Any]:
    """Everything the settings page shows about this machine and its models."""
    hw = hardware.detect()
    installed = _installed()
    models: List[Dict[str, Any]] = []
    for info in installed:
        facts = _facts(info)
        fit = None
        if facts["weights_gb"] is not None:
            ctx = min(settings.local_num_ctx, catalog.best_context(hw, facts["weights_gb"], facts["params_b"], facts["kv"], settings.local_num_ctx))
            fit = catalog.assess(hw, facts["weights_gb"], facts["params_b"], facts["kv"], ctx)
        lic = facts["license"] or {"id": "unknown", "name": "Not reported by Ollama", "commercial": "review"}
        models.append(
            {
                "id": info.id,
                "size_gb": round(info.size_bytes / 1e9, 1) if info.size_bytes else None,
                "fit": fit,
                "license": {**lic, "source": "model file"},
                "commercial_ok": lic["commercial"] == "yes",
                "verified": facts["catalog"] is not None,
            }
        )
    recommendation = catalog.recommend(hw, [m.id for m in installed], settings.commercial_use, settings.local_num_ctx)
    return {
        "hardware": hw.to_dict(),
        "deployment": hardware.deployment(),
        "models": models,
        "recommendation": recommendation,
        "commercial_only": settings.commercial_use,
    }
