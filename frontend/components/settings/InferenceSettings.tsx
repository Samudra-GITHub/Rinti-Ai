"use client";

import { useCallback, useEffect, useState } from "react";
import { HardDrive, Cloud, Laptop, TriangleAlert } from "lucide-react";
import { SectionLabel } from "@/components/layout/PageShell";
import { SettingsCard } from "@/components/settings/SettingsCard";
import { Button } from "@/ui/Button";
import { Segmented } from "@/ui/Segmented";
import { Select } from "@/ui/Select";
import { Switch } from "@/ui/Switch";
import {
  api,
  type AlternativeDto,
  type InferenceMode,
  type InferenceStatusDto,
  type LocalModelDto,
  type RecommendationCandidateDto,
} from "@/lib/api";
import { cn } from "@/lib/cn";

function modeHelp(mode: InferenceMode, fallback: boolean): string {
  if (mode === "local")
    return "Everything runs on the computer hosting Rinti. Conversations never leave it, and there is no cloud fallback.";
  if (mode === "cloud") return "Every reply is generated by the cloud provider (uses its API quota).";
  return fallback
    ? "Uses a model on this computer first, choosing one that suits it. If that fails before replying, the cloud model answers instead."
    : "Uses the best model that suits this computer. The cloud is never used unless you turn the fallback on below.";
}

const SPEED_LABEL: Record<string, string> = {
  fast: "runs fast",
  moderate: "runs at moderate speed",
  slow: "runs slowly",
  "not suitable": "not suitable",
};

function StatusDot({ ok }: { ok: boolean }) {
  return (
    <span
      aria-hidden
      className={cn("inline-block h-2 w-2 rounded-full", ok ? "bg-accent shadow-[0_0_8px_rgb(var(--accent)/0.8)]" : "bg-red-500")}
    />
  );
}

function modelLabel(m: LocalModelDto): string {
  const parts = [m.id];
  if (m.size_gb) parts[0] += ` (${m.size_gb} GB)`;
  parts.push(m.license.id === "unknown" ? "licence unknown" : m.license.id);
  if (m.fit) parts.push(m.fit.fits ? m.fit.speed : "too large for this computer");
  return parts.join(" · ");
}

function licenceNote(c: { license: { name: string; commercial: string } }): string {
  if (c.license.commercial === "yes") return `${c.license.name}, commercial use allowed`;
  if (c.license.commercial === "no") return `${c.license.name}, not for commercial use`;
  return `${c.license.name}, check the terms before commercial use`;
}

/** Where replies are generated: this computer (Ollama) or the cloud, and with which models. */
export function InferenceSettings() {
  const [status, setStatus] = useState<InferenceStatusDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);

  const load = useCallback(async () => {
    try {
      setStatus(await api.getInferenceStatus());
      setError(null);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Couldn't load the model setup.");
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  async function save(update: Parameters<typeof api.updateInferenceConfig>[0]) {
    setSaving(true);
    setError(null);
    try {
      await api.updateInferenceConfig(update);
      await load();
    } catch (e) {
      setError(e instanceof Error ? e.message : "Couldn't save that change.");
    } finally {
      setSaving(false);
    }
  }

  if (!status) {
    return (
      <>
        <SectionLabel>Where Rinti runs</SectionLabel>
        {error ? (
          <p role="alert" className="px-1 py-3 text-[13px] text-red-600 dark:text-red-300">
            {error}
          </p>
        ) : (
          <div className="mt-3 h-16 animate-pulse rounded-2xl bg-fg/[0.05]" role="status" aria-label="Loading model setup" />
        )}
      </>
    );
  }

  const cloud = status.cloud.find((c) => c.id === status.cloud_provider);
  const cloudReady = Boolean(cloud?.configured);
  const locked = !status.can_configure || saving;
  const installed = status.local.models;
  const loaded = status.local.loaded[0];
  const { hardware, deployment, assessment, recommendation } = status;
  const hasModel = (id: string) => installed.some((m) => m.id === id);

  function runAlternative(alt: AlternativeDto) {
    if (alt.action === "use_model" && alt.model) save({ local_model: alt.model, coding_model: alt.model });
    if (alt.action === "switch_mode" && alt.mode) save({ mode: alt.mode });
  }

  return (
    <>
      <SectionLabel>Where Rinti runs</SectionLabel>
      <SettingsCard title="Inference" description={modeHelp(status.mode, status.cloud_fallback)}>
        <Segmented<InferenceMode>
          label="Inference mode"
          value={status.mode}
          onChange={(mode) => !locked && save({ mode })}
          options={[
            { value: "local", label: "Local only", icon: <Laptop size={13} /> },
            { value: "auto", label: "Auto", icon: <HardDrive size={13} /> },
            ...(cloudReady ? [{ value: "cloud" as const, label: "Cloud", icon: <Cloud size={13} /> }] : []),
          ]}
        />
      </SettingsCard>
      {status.mode === "auto" && (
        <SettingsCard
          title="Allow cloud fallback"
          description={
            cloudReady
              ? "If the local model fails before replying, let the cloud model answer. Off keeps every conversation on this computer."
              : "No cloud API key is set on the server, so a cloud fallback isn't available."
          }
        >
          <Switch
            label="Allow cloud fallback"
            checked={status.cloud_fallback}
            disabled={locked || !cloudReady}
            onCheckedChange={(cloud_fallback) => save({ cloud_fallback })}
          />
        </SettingsCard>
      )}
      {!status.can_configure && (
        <p className="px-1 pb-2 text-[13px] text-fg/45">
          These settings can only be changed from the computer running Rinti, or with an admin token. Showing the current setup.
        </p>
      )}
      {error && (
        <p role="alert" className="px-1 pb-2 text-[13px] text-red-600 dark:text-red-300">
          {error}
        </p>
      )}

      {status.mode !== "cloud" && assessment.level !== "good" && (
        <div
          role="status"
          className="my-3 rounded-2xl border border-amber-400/30 bg-amber-500/10 px-4 py-3 text-[13px] leading-relaxed text-fg/80"
        >
          <p className="flex items-center gap-2 font-medium text-fg/90">
            <TriangleAlert size={14} aria-hidden />
            {assessment.level === "slow" ? "Local replies will be slower here" : "Local replies aren't available right now"}
          </p>
          <ul className="mt-1.5 list-disc pl-5">
            {assessment.problems.map((p) => (
              <li key={p}>{p}</li>
            ))}
          </ul>
          <p className="mt-2 text-fg/60">Nothing is switched for you. Your options:</p>
          <ul className="mt-2 space-y-2">
            {assessment.alternatives.map((alt) => (
              <li key={alt.text} className="flex flex-wrap items-center justify-between gap-2">
                <span>{alt.text}</span>
                {alt.action !== "install_model" && (
                  <Button
                    size="sm"
                    variant="secondary"
                    disabled={locked || (alt.action === "switch_mode" && !cloudReady)}
                    onClick={() => runAlternative(alt)}
                  >
                    {alt.action === "use_model" ? "Use it" : "Switch"}
                  </Button>
                )}
              </li>
            ))}
          </ul>
        </div>
      )}

      <SettingsCard
        title="Computer running Rinti"
        description={`${deployment.note}${hardware?.notes.length ? " " + hardware.notes.join(" ") : ""}`}
      >
        {hardware ? (
          <div className="text-right text-[13px] leading-relaxed text-fg/70">
            <div>
              {hardware.ram_total_gb} GB memory
              {hardware.ram_available_gb !== null ? ` (${hardware.ram_available_gb} GB free)` : ""}
            </div>
            <div>
              {hardware.gpu ? `${hardware.gpu.name}, ${hardware.gpu.vram_total_gb} GB` : "No supported graphics card found"}
            </div>
          </div>
        ) : (
          <span className="text-[13px] text-fg/45">Not shown</span>
        )}
      </SettingsCard>

      <SettingsCard
        title="Local model server"
        description={
          status.local.reachable
            ? `Ollama is running with ${installed.length} model${installed.length === 1 ? "" : "s"} installed.`
            : deployment.hosted
              ? "This server has no Ollama, and it can't reach models on your own computer."
              : "Ollama isn't reachable. Start it (run `ollama serve`) to use local models."
        }
      >
        <span className="flex items-center gap-2 text-[13px] text-fg/70">
          <StatusDot ok={status.local.reachable} />
          {status.local.reachable ? "Running" : "Not running"}
        </span>
      </SettingsCard>

      <SettingsCard
        title="Suggested model"
        description={
          recommendation.recommended
            ? `${recommendation.summary} ${licenceNote(recommendation.recommended)}. ${recommendation.recommended.tested === "pending" ? "Not yet benchmarked in Rinti." : recommendation.recommended.tested}`
            : recommendation.summary
        }
      >
        <span className="text-[13px] text-fg/45">
          {recommendation.recommended ? `${recommendation.recommended.download_gb} GB download` : ""}
        </span>
      </SettingsCard>
      <details className="px-1 pb-2 text-[13px] text-fg/55">
        <summary className="cursor-pointer select-none py-1 text-fg/70">How each verified model fits this computer</summary>
        <ul className="mt-2 space-y-2">
          {recommendation.candidates.map((c: RecommendationCandidateDto) => (
            <li key={c.model}>
              <span className="text-fg/80">{c.label}</span> ({c.download_gb} GB, {c.installed ? "installed" : "not installed"}):{" "}
              {SPEED_LABEL[c.fit.speed] ?? c.fit.speed} with a {c.context.toLocaleString()} token window. {licenceNote(c)}.
              {c.fit.reasons.length ? ` ${c.fit.reasons.join(" ")}` : ""}
            </li>
          ))}
        </ul>
        <p className="mt-2">
          Memory figures are estimates, checked against measurements on one computer. Models you install yourself are listed
          from their own licence text and are never suggested automatically.
        </p>
      </details>

      {status.mode !== "cloud" && (
        <>
          <SettingsCard
            title="Everyday model"
            description={
              status.local.general_ready
                ? "Answers general questions, writing and research."
                : `${status.local_model} isn't installed. Install it with: ollama pull ${status.local_model}`
            }
          >
            <Select
              aria-label="Everyday local model"
              value={hasModel(status.local_model) ? status.local_model : ""}
              disabled={locked || installed.length === 0}
              onChange={(e) => save({ local_model: e.target.value })}
            >
              {!hasModel(status.local_model) && <option value="">Not installed</option>}
              {installed.map((m) => (
                <option key={m.id} value={m.id}>
                  {modelLabel(m)}
                </option>
              ))}
            </Select>
          </SettingsCard>
          <SettingsCard
            title="Coding model"
            description="Used for programming questions. It can be the same as the everyday model."
          >
            <Select
              aria-label="Coding local model"
              value={hasModel(status.coding_model) ? status.coding_model : ""}
              disabled={locked || installed.length === 0}
              onChange={(e) => save({ coding_model: e.target.value })}
            >
              {!hasModel(status.coding_model) && <option value="">Not installed</option>}
              {installed.map((m) => (
                <option key={m.id} value={m.id}>
                  {modelLabel(m)}
                </option>
              ))}
            </Select>
          </SettingsCard>
          {loaded && (
            <SettingsCard
              title="In memory now"
              description={`${loaded.model} is loaded${
                loaded.size_gb ? `, using ${loaded.size_gb} GB (${loaded.gpu_gb} GB on the graphics card)` : ""
              }.`}
            >
              <span className="text-[13px] text-fg/45">{loaded.context ? `${loaded.context.toLocaleString()} token window` : ""}</span>
            </SettingsCard>
          )}
        </>
      )}

      <SettingsCard
        title="Cloud provider"
        description={
          cloudReady
            ? `${cloud?.label} is configured (${status.cloud_model}).`
            : "No cloud API key is set on the server. Local models work without one."
        }
      >
        <span className="flex items-center gap-2 text-[13px] text-fg/70">
          <StatusDot ok={cloudReady} />
          {cloudReady ? "Configured" : "Not configured"}
        </span>
      </SettingsCard>
    </>
  );
}
